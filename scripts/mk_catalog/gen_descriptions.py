CONNECT_3 = ["특히 ", "실제로 ", "실사용 후기를 보면 ", ""]


def strip_period(s):
    return s[:-1] if s.endswith(".") else s


def gen_desc(c):
    info = CAT_INFO.get(c["cat"], CAT_INFO["기타"])
    head = pick(info["heads"], c["code"] + "H")
    space = pick(info["spaces"], c["code"] + "S")
    persona = info["persona"]
    points = info["points"]

    # 1문단: 공감형 도입 + 이 제품이 어디에 어울리는지 자연스럽게 이어서
    c1 = pick(CONNECT_1, c["code"] + "c1")
    p1 = f"{head}, {c['name']}을 살펴보세요. {c1}{persona}을 위해 만들어진 제품이라, {space}에 달아두면 특히 만족스러울 거예요."

    # 2문단: 구매 포인트를 나열이 아니라 이어지는 문장으로 (원래 완전한 문장을 그대로 접속사로 연결)
    sentences = [s for s in points if s]
    p2_parts = []
    if len(sentences) > 0:
        p2_parts.append(sentences[0])
    if len(sentences) > 1:
        c2 = pick(CONNECT_2, c["code"] + "c2")
        p2_parts.append(c2 + sentences[1])
    if len(sentences) > 2:
        c3 = pick(CONNECT_3, c["code"] + "c3")
        p2_parts.append(c3 + sentences[2])
    p2 = " ".join(p2_parts)

    # 3문단: 색감/조도/평수 정보를 자연스럽게
    mood_bits = []
    ct_text = (c.get("ct") or "") + " " + (c.get("features") or "")
    for pat, msg in CT_MOOD:
        if re.search(pat, ct_text):
            mood_bits.append(strip_period(msg))
            break
    color_text = c.get("color") or ""
    for pat, msg in COLOR_TONE:
        if re.search(pat, color_text):
            mood_bits.append(strip_period(msg))
            break
    rh = room_hint(c.get("led"), c.get("features"))
    if rh:
        mood_bits.append(strip_period(rh))

    p3 = ""
    if mood_bits:
        p3 = ", ".join(mood_bits) + "."

    paragraphs = [p1, p2]
    if p3:
        paragraphs.append(p3)

    if c["src"] == "blog-new":
        paragraphs.append(
            "이 제품은 저희 블로그에는 소개돼 있지만 아직 정식 카탈로그에는 실리지 않은 신상품이에요. "
            "정확한 공급가는 확인 중이니 문의해주시면 안내해드릴게요."
        )

    body = "\n\n".join(paragraphs)

    spec_bits = []
    if c.get("size"):
        spec_bits.append(f"규격 {c['size']}")
    if c.get("led"):
        spec_bits.append(f"광원 {c['led']}")
    if c.get("color"):
        spec_bits.append(f"색상 {c['color']}")
    if c.get("ct"):
        spec_bits.append(f"색온도 {c['ct']}")
    if c.get("features"):
        spec_bits.append(c["features"])

    if spec_bits:
        body += "\n\n" + " · ".join(spec_bits)

    return body


for c in catalog:
    c["desc"] = gen_desc(c)

json.dump(catalog, Path("data/mk_catalog/products_web.json").open("w", encoding="utf-8"), ensure_ascii=False)
