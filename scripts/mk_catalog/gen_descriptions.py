def room_hint(led, features):
    text = (led or "") + " " + (features or "")
    m = re.search(r"(\d{1,4})\s?W", text)
    if not m:
        return None
    w = int(m.group(1))
    if w <= 8:
        return f"{w}W급 — 1~2평 소형 공간이나 포인트 조명으로 알맞습니다."
    if w <= 15:
        return f"{w}W급 — 2~4평 작은 방이나 보조 조명으로 적당합니다."
    if w <= 25:
        return f"{w}W급 — 4~6평 방을 밝히기에 무난합니다."
    if w <= 40:
        return f"{w}W급 — 6~8평 방을 메인 조명으로 채울 수 있습니다."
    if w <= 60:
        return f"{w}W급 — 8~10평 거실도 환하게 밝힐 수 있습니다."
    if w <= 100:
        return f"{w}W급 — 10~15평 넓은 거실이나 상업 공간에 알맞습니다."
    return f"{w}W급 — 15평 이상 대형 공간·매장·현장에 적합한 고출력입니다."


def pick(seq, salt):
    if not seq:
        return ""
    # salt 기반 결정적 선택일 뿐 보안 용도 아님(bandit B324, 2026-09-29 확인).
    idx = int(hashlib.md5(salt.encode("utf-8"), usedforsecurity=False).hexdigest(), 16) % len(seq)
    return seq[idx]


