async def post_draft(page, post: dict):
    """한 편의 블로그 초안을 작성하고 임시저장."""
    no = post["no"]
    print(f"\n[{no:02d}/20편] 작성 시작: {post['title'][:30]}...")

    # 새 글쓰기 페이지로 이동
    await page.goto(NEW_POST_URL, wait_until="domcontentloaded", timeout=30000)
    await asyncio.sleep(3)

    # 팝업 닫기 시도
    for sel in ['button:has-text("닫기")', 'button:has-text("확인")', ".popup_close"]:
        try:
            await page.click(sel, timeout=1500)
            await asyncio.sleep(0.5)
        except Exception:  # noqa: BLE001 - 임시저장 전 옵션 요소 클릭 실패는 무시하고 계속 진행 — 발행이 아닌 임시저장 단계
            pass

    # 제목 입력
    title_area = await page.query_selector(".se-title-text")
    if title_area:
        await title_area.click()
        await page.keyboard.press("Control+A")
        await page.keyboard.press("Delete")
        await asyncio.sleep(0.2)
        await title_area.type(post["title"])
    print("  ✓ 제목 입력")

    await asyncio.sleep(0.5)

    # 본문 입력
    content_area = await page.query_selector("[role=textbox], .se-content")
    if content_area:
        await content_area.click()
        await page.keyboard.press("Control+A")
        await page.keyboard.press("Delete")
        await asyncio.sleep(0.3)
        lines = post["body"].split("\n")
        for line in lines:
            if line:
                await page.keyboard.type(line)
            await page.keyboard.press("Enter")
    print("  ✓ 본문 입력")

    # 저장 (임시저장)
    await page.click(".save_btn__bzc5B", timeout=5000)
    await asyncio.sleep(2)
    print("  ✓ 임시저장 완료")

    # 발행 패널 열고 태그 입력
    try:
        await page.click(".publish_btn__m9KHH", timeout=5000)
        await asyncio.sleep(1.5)
        tag_input = page.locator("#tag-input")
        for tag in post["tags"]:
            await tag_input.click()
            await asyncio.sleep(0.2)
            await tag_input.fill(tag)
            await asyncio.sleep(0.2)
            await page.keyboard.press("Enter")
            await asyncio.sleep(0.3)
        print(f"  ✓ 태그 {len(post['tags'])}개 입력")

        # 패널 닫고 재저장
        await page.keyboard.press("Escape")
        await asyncio.sleep(0.3)
        await page.click(".save_btn__bzc5B", timeout=5000)
        await asyncio.sleep(1.5)
        print("  ✓ 태그 포함 재저장")
    except Exception as e:  # noqa: BLE001 - 블로그 임시저장 CLI 자동화 — 옵션 클릭/태그 재저장 실패는 무시하고 계속하거나 개별 글 실패 시 다음 글로 continue, 임시저장(발행 아님)이며 실패해도 데이터 손실 없음
        print(f"  ⚠ 태그 입력 실패: {e}")

    print(f"[{no:02d}/20편] 완료 ✅")


